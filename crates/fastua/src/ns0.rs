//! The complete namespace 0 of the OPC UA specification.
//!
//! `data/ns0.bin` holds every node of the official `Opc.Ua.NodeSet2.xml`,
//! compiled by `tools/gen_ns0.py` (format described there). The address
//! space builder first creates the nodes fastua serves live values for, then
//! merges this table: missing nodes are added with their static values, and
//! missing references are added to every node. Nothing here runs on the
//! request path.

use crate::address_space::{NodeKind, ValueSource, ACCESS_READ};
use crate::codec::{DResult, DecodeError, Reader};
use crate::types::*;

include!("ns0_ref_types.rs");

static NODESET: &[u8] = include_bytes!("../data/ns0.bin");

/// One node of the nodeset, with its references to other namespace 0 nodes.
pub struct Ns0Node {
    pub id: u32,
    pub browse_name: QualifiedName,
    pub display_name: LocalizedText,
    pub description: Option<LocalizedText>,
    pub kind: NodeKind,
    /// (reference type, forward, target id).
    pub refs: Vec<(u32, bool, u32)>,
}

fn opt_text(r: &mut Reader) -> DResult<Option<LocalizedText>> {
    Ok(if r.u8()? != 0 { Some(r.localized_text()?) } else { None })
}

fn node(r: &mut Reader) -> DResult<Ns0Node> {
    let id = r.u32()?;
    let class = r.u8()?;
    let browse_name = r.qualified_name()?;
    let display_name = r.localized_text()?;
    let description = opt_text(r)?;
    let kind = match class {
        1 => NodeKind::Object { event_notifier: r.u8()? },
        2 => {
            let data_type = NodeId::ns0(r.u32()?);
            let value_rank = r.i32()?;
            // Only read access is ever granted on standard nodes.
            let _access = r.u8()?;
            let value = if r.u8()? != 0 { r.variant()? } else { Variant::Empty };
            NodeKind::Variable { data_type, value_rank, access: ACCESS_READ, value: ValueSource::Static(value) }
        }
        // Standard methods are executable only where fastua implements them.
        4 => NodeKind::Method { executable: false },
        8 => NodeKind::ObjectType { is_abstract: r.u8()? != 0 },
        16 => {
            let is_abstract = r.u8()? != 0;
            NodeKind::VariableType { is_abstract, data_type: NodeId::ns0(r.u32()?), value_rank: r.i32()? }
        }
        32 => {
            let is_abstract = r.u8()? != 0;
            let symmetric = r.u8()? != 0;
            NodeKind::ReferenceType { is_abstract, symmetric, inverse_name: opt_text(r)? }
        }
        64 => NodeKind::DataType { is_abstract: r.u8()? != 0 },
        _ => return Err(DecodeError),
    };
    let n = r.u32()? as usize;
    let mut refs = Vec::with_capacity(n);
    for _ in 0..n {
        let t = r.u32()?;
        let fwd = r.u8()? != 0;
        refs.push((t, fwd, r.u32()?));
    }
    Ok(Ns0Node { id, browse_name, display_name, description, kind, refs })
}

/// Decodes the whole nodeset.
pub fn nodes() -> Vec<Ns0Node> {
    let mut r = Reader::new(NODESET);
    let parse = |r: &mut Reader| -> DResult<Vec<Ns0Node>> {
        if r.take(4)? != b"FUA0" {
            return Err(DecodeError);
        }
        let n = r.u32()? as usize;
        let mut out = Vec::with_capacity(n);
        for _ in 0..n {
            out.push(node(r)?);
        }
        Ok(out)
    };
    parse(&mut r).expect("data/ns0.bin is generated by tools/gen_ns0.py")
}

/// Parent of a standard reference type.
#[inline]
pub fn ref_type_parent(t: u32) -> Option<u32> {
    REF_TYPE_PARENT.binary_search_by_key(&t, |&(c, _)| c).ok().map(|i| REF_TYPE_PARENT[i].1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn decodes_the_whole_nodeset() {
        let nodes = nodes();
        assert!(nodes.len() > 5000, "{}", nodes.len());
        let server = nodes.iter().find(|n| n.id == 2253).unwrap();
        assert_eq!(&*server.browse_name.name, "Server");
        assert!(REF_TYPE_PARENT.windows(2).all(|w| w[0].0 < w[1].0));
        assert_eq!(ref_type_parent(47), Some(44)); // HasComponent -> Aggregates
        assert_eq!(ref_type_parent(31), None);
    }
}
